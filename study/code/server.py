"""
The web server of the study (README, "Online"), with the standard library only.  Every session of every
participant has its own link, and several participants can answer at the same time.

  /s/<token>/              the session's page (ui.html): instructions, two practice questions, the questions, the
                           exit questionnaire; reopening the link continues the session where it is
  /s/<token>/api/...       meta, question, answer, stop, practice, questionnaire
  /s/<token>/docs/<file>   the documentation of the relation (conditions E and P only): the files in docs/<relation>/,
                           and links to the official documents listed in docs/<relation>/links.json
  /admin                   for the experimenter, after the admin key: every link, the state of every session, the
                           session files and a zip of them, and a reset for the test codes
  /healthz                 for the uptime monitor (GET or HEAD)

The token of a session is HMAC-SHA256(STUDY_SECRET, "<participant>/<session>"), so links cannot be guessed and need
no table; they stay the same as long as STUDY_SECRET does.  The codes are E01-E03, P01-P03, U01-U03, and TE01 ...
TU03 for tests that are not part of the study (the experimenter's own tries, the pilot), whose files go to
sessions/test/.  Session files are kept by store.py.

Locally:   python server.py [--port 8765]   prints the admin link; the secrets are kept in code/.local_secrets.json
On Render: render.yaml at the root of the repository (STUDY_SECRET, STUDY_ADMIN_KEY generated by Render;
           STUDY_GITHUB_REPO and STUDY_GITHUB_TOKEN set by hand for durable storage).
"""
import argparse, base64, hashlib, hmac, html, io, json, mimetypes, os, secrets, signal, sys, threading, time
import traceback, urllib.parse, zipfile
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common as K
import session as S
from store import Store

UI = os.path.join(K.HERE, "ui.html")
DOCS = os.path.join(K.KIT, "docs")
SESSIONS = os.path.join(K.KIT, "sessions")
CODES = [c + n for c in K.CONDITIONS for n in sorted(K.ASSIGN)]
TESTS = ["T" + c for c in CODES]
LIVE, LIVE_LOCK = {}, threading.Lock()
CFG = {}


def secrets_():
    s, a = os.environ.get("STUDY_SECRET"), os.environ.get("STUDY_ADMIN_KEY")
    if s and a:
        return s, a
    path = os.path.join(K.HERE, ".local_secrets.json")          # local runs only
    if not os.path.exists(path):
        with open(path, "w", encoding="utf-8") as fh:
            json.dump({"secret": secrets.token_hex(32), "admin": secrets.token_urlsafe(12)}, fh)
    with open(path, encoding="utf-8") as fh:
        d = json.load(fh)
    return d["secret"], d["admin"]


def token(code, sno):
    mac = hmac.new(CFG["secret"].encode(), f"{code}/{sno}".encode(), hashlib.sha256).digest()
    return base64.b32encode(mac[:15]).decode().lower()


TOKENS = {}                                                     # token -> (code, session)


def folder(code):
    return os.path.join(SESSIONS, "test") if code.startswith("T") else SESSIONS


def file_of(code, sno):
    return os.path.join(folder(code), f"{code}_s{sno}_{K.relation_of(code, sno)}.jsonl")


def session_for(code, sno):
    with LIVE_LOCK:
        s = LIVE.get((code, sno))
        if s is None:
            s = S.Session(code, sno, folder(code), live_minutes=CFG["minutes"], on_write=CFG["store"].changed)
            LIVE[(code, sno)] = s
        return s


def meta(s):
    docs = []
    if s.condition in ("E", "P"):
        d = os.path.join(DOCS, s.ds)
        if os.path.isdir(d):
            for f in sorted(os.listdir(d)):
                if f == "links.json":
                    with open(os.path.join(d, f), encoding="utf-8") as fh:
                        docs += [{"name": x["name"], "href": x["url"]} for x in json.load(fh)]
                elif not f.startswith(".") and f != "README.md":
                    docs.append({"name": f, "href": "docs/" + urllib.parse.quote(f)})
    return {"session_no": s.session_no, "condition": s.condition, "relation": s.ds, "attributes": s.rel.names,
            "sample": s.rel.sample, "rows": s.rel.rows, "docs": docs, **s.progress()}


def overview():
    rows = []
    for code in CODES + TESTS:
        for sno in (1, 2):
            p = file_of(code, sno)
            st = S.status(p)
            n = sum(r["event"] == "answer" for r in S.read(p)) if st != "new" else 0
            rows.append({"code": code, "session": sno, "relation": K.relation_of(code, sno), "state": st,
                         "answers": n, "token": token(code, sno), "file": os.path.relpath(p, SESSIONS),
                         "modified": time.strftime("%Y-%m-%d %H:%M", time.localtime(os.path.getmtime(p)))
                         if st != "new" else ""})
    return rows


def admin_page(base):
    st = CFG["store"].state()
    warn = ("" if st["durable"] else
            "<p class=warn><b>Storage is not durable.</b> STUDY_GITHUB_REPO and STUDY_GITHUB_TOKEN are not set, so "
            "the session files live on this instance's disk only, which Render wipes at every restart or deploy. "
            "Do not run real sessions like this.</p>")
    st_line = (f"storage: {'GitHub ' + html.escape(st['repo']) if st['durable'] else 'local disk only'}; "
               f"files put {st['puts']}, last {st['last_sync'] or '-'}, waiting {st['pending']}"
               + (f"; last error {html.escape(st['last_error'])}" if st["last_error"] else ""))
    trs = []
    for r in overview():
        link = f"{base}/s/{r['token']}/"
        f = (f"<a href='/admin/file?name={urllib.parse.quote(r['file'])}'>file</a>" if r["state"] != "new" else "")
        reset = (f"<form method=post action='/admin/reset' onsubmit=\"return confirm('Delete this test session?')\">"
                 f"<input type=hidden name=code value={r['code']}><input type=hidden name=session value={r['session']}>"
                 f"<button>reset</button></form>" if r["code"].startswith("T") and r["state"] != "new" else "")
        trs.append(f"<tr class={'test' if r['code'].startswith('T') else ''}><td>{r['code']}</td><td>{r['session']}"
                   f"</td><td>{r['relation']}</td><td><input readonly size=60 value='{link}' onclick='this.select()'>"
                   f"</td><td>{r['state']}</td><td>{r['answers']}</td><td>{r['modified']}</td><td>{f}</td>"
                   f"<td>{reset}</td></tr>")
    return f"""<!doctype html><meta charset=utf-8><title>Study admin</title>
<style>body{{font:14px system-ui,sans-serif;margin:24px;background:#fff;color:#1d2530}} table{{border-collapse:collapse}}
td,th{{border-bottom:1px solid #ddd;padding:4px 8px;text-align:left}} tr.test{{color:#777}}
.warn{{background:#fde8e8;border:1px solid #e0a0a0;padding:8px 12px;border-radius:6px;max-width:900px}}
input{{font:12px monospace}} form{{margin:0}}</style>
<h1>Rules of a table: study admin</h1>{warn}<p>{st_line}</p>
<p><a href='/admin/zip'>all session files (zip)</a></p>
<p>Codes T… are tests, not part of the study (their files are in sessions/test/). A link opens its session; reopening it
continues where the participant was. Send each participant only their own link.</p>
<table><tr><th>code</th><th>session</th><th>relation</th><th>link</th><th>state</th><th>answers</th><th>modified</th>
<th></th><th></th></tr>{''.join(trs)}</table>"""


LOGIN = """<!doctype html><meta charset=utf-8><title>Study admin</title>
<form method=post action='/admin/login' style='font:16px system-ui;margin:40px'>Admin key:
<input type=password name=key autofocus> <button>Open</button></form>"""


class Handler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"

    def log_message(self, fmt, *a):
        pass

    def send(self, code, body, ctype="application/json; charset=utf-8", headers=()):
        data = body if isinstance(body, bytes) else (body.encode("utf-8") if isinstance(body, str) else
                                                     json.dumps(body, ensure_ascii=False).encode("utf-8"))
        self.send_response(code)
        self.send_header("Content-Type", ctype)
        self.send_header("Cache-Control", "no-store")
        self.send_header("Content-Length", str(len(data)))
        for k, v in headers:
            self.send_header(k, v)
        self.end_headers()
        if self.command != "HEAD":
            self.wfile.write(data)

    def redirect(self, to, headers=()):
        self.send(303, b"", "text/plain", [("Location", to), *headers])

    def body(self):
        n = int(self.headers.get("Content-Length") or 0)
        raw = self.rfile.read(n) if n else b""
        if self.headers.get("Content-Type", "").startswith("application/x-www-form-urlencoded"):
            return {k: v[0] for k, v in urllib.parse.parse_qs(raw.decode()).items()}
        return json.loads(raw or b"{}")

    def is_admin(self):
        c = self.headers.get("Cookie", "")
        want = hmac.new(CFG["secret"].encode(), b"admin", hashlib.sha256).hexdigest()
        return any(hmac.compare_digest(p.strip(), "admin=" + want) for p in c.split(";"))

    def base(self):
        ext = os.environ.get("RENDER_EXTERNAL_URL")
        return ext.rstrip("/") if ext else f"http://{self.headers.get('Host', 'localhost')}"

    def handle_one_request(self):
        try:
            super().handle_one_request()
        except Exception:                                       # noqa: BLE001 (logged, answered with 500, closed)
            traceback.print_exc()
            self.close_connection = True
            try:
                self.send(500, {"error": "server"})
            except Exception:                                   # noqa: BLE001
                pass

    def do_HEAD(self):
        self.do_GET()

    def do_GET(self):
        u = urllib.parse.urlparse(self.path)
        path = u.path
        if path == "/healthz":
            return self.send(200, b"ok", "text/plain")
        if path == "/":
            return self.send(200, b"Rules of a table: please use the link you were given.", "text/plain")
        if path.startswith("/admin"):
            if not self.is_admin():
                return self.send(200, LOGIN, "text/html; charset=utf-8")
            if path == "/admin":
                return self.send(200, admin_page(self.base()), "text/html; charset=utf-8")
            if path == "/admin/file":
                name = urllib.parse.parse_qs(u.query).get("name", [""])[0]
                p = os.path.normpath(os.path.join(SESSIONS, name))
                if p.startswith(SESSIONS + os.sep) and p.endswith(".jsonl") and os.path.isfile(p):
                    with open(p, "rb") as fh:
                        return self.send(200, fh.read(), "application/x-ndjson",
                                         [("Content-Disposition", f"attachment; filename={os.path.basename(p)}")])
            if path == "/admin/zip":
                buf = io.BytesIO()
                with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
                    for root, _, files in os.walk(SESSIONS):
                        for f in files:
                            if f.endswith(".jsonl"):
                                p = os.path.join(root, f)
                                z.write(p, os.path.relpath(p, SESSIONS))
                return self.send(200, buf.getvalue(), "application/zip",
                                 [("Content-Disposition", f"attachment; filename=sessions_{time.strftime('%Y%m%d_%H%M')}.zip")])
            return self.send(404, {"error": "not found"})
        parts = path.split("/")
        if len(parts) >= 3 and parts[1] == "s" and parts[2] in TOKENS:
            code, sno = TOKENS[parts[2]]
            rest = "/".join(parts[3:])
            if len(parts) == 3:
                return self.redirect(path + "/")
            if rest == "":
                with open(UI, "rb") as fh:
                    return self.send(200, fh.read(), "text/html; charset=utf-8")
            s = session_for(code, sno)
            if rest == "api/meta":
                return self.send(200, meta(s))
            if rest == "api/question":
                return self.send(200, s.question())
            if rest.startswith("docs/") and s.condition in ("E", "P"):
                f = os.path.join(DOCS, s.ds, os.path.basename(urllib.parse.unquote(rest[len("docs/"):])))
                if os.path.isfile(f):
                    with open(f, "rb") as fh:
                        return self.send(200, fh.read(), mimetypes.guess_type(f)[0] or "application/octet-stream")
        return self.send(404, {"error": "not found"})

    def do_POST(self):
        path = urllib.parse.urlparse(self.path).path
        b = self.body()
        if path == "/admin/login":
            if hmac.compare_digest(str(b.get("key", "")), CFG["admin"]):
                c = hmac.new(CFG["secret"].encode(), b"admin", hashlib.sha256).hexdigest()
                return self.redirect("/admin", [("Set-Cookie", f"admin={c}; HttpOnly; SameSite=Strict; Path=/admin")])
            return self.send(403, LOGIN, "text/html; charset=utf-8")
        if path == "/admin/reset" and self.is_admin():
            code, sno = b.get("code", ""), int(b.get("session", 0))
            if code in TESTS and sno in (1, 2):
                with LIVE_LOCK:
                    old = LIVE.pop((code, sno), None)
                    if old is not None and old.fh is not None and not old.fh.closed:
                        old.fh.close()
                    CFG["store"].delete(file_of(code, sno))
            return self.redirect("/admin")
        parts = path.split("/")
        if len(parts) >= 4 and parts[1] == "s" and parts[2] in TOKENS:
            s = session_for(*TOKENS[parts[2]])
            rest = "/".join(parts[3:])
            if rest == "api/answer":
                if b.get("answer") not in ("yes", "no", "dk"):
                    return self.send(400, {"error": "answer"})
                rt = b.get("rt_ms")
                return self.send(200, s.answer(str(b.get("qid")), b["answer"], rt if isinstance(rt, int) else None))
            if rest == "api/stop":
                return self.send(200, s.stop("voluntary"))
            if rest == "api/practice":
                s.practice({"practice": b.get("practice"), "answer": b.get("answer")})
                return self.send(200, {"ok": True})
            if rest == "api/questionnaire":
                keep = {k: b.get(k) for k in ("familiarity", "fatigue", "confidence")}
                keep.update({k: str(b.get(k) or "")[:2000] for k in ("stop_reason", "comments")})
                s.questionnaire(keep)
                return self.send(200, {"ok": True})
        return self.send(404, {"error": "not found"})


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--port", type=int, default=int(os.environ.get("PORT", 8765)))
    ap.add_argument("--host", default="0.0.0.0" if os.environ.get("PORT") else "127.0.0.1")
    ap.add_argument("--minutes", type=float, default=S.LIVE_MINUTES)
    a = ap.parse_args()
    CFG["secret"], CFG["admin"] = secrets_()
    CFG["minutes"] = a.minutes
    store = Store(SESSIONS, os.environ.get("STUDY_GITHUB_REPO"), os.environ.get("STUDY_GITHUB_TOKEN"),
                  os.environ.get("STUDY_GITHUB_BRANCH", "main"))
    CFG["store"] = store
    print("fetched", store.fetch_all(), "session files;", "durable" if store.durable else "LOCAL DISK ONLY", flush=True)
    store.start()
    for code in CODES + TESTS:
        for sno in (1, 2):
            TOKENS[token(code, sno)] = (code, sno)
    for ds in K.RELATIONS.values():
        K.prebuilt(ds)                                          # read the pickles once

    def bye(*_):
        store.flush()
        os._exit(0)
    signal.signal(signal.SIGTERM, bye)
    srv = ThreadingHTTPServer((a.host, a.port), Handler)
    srv.daemon_threads = True
    print(f"listening on {a.host}:{a.port}", flush=True)
    if not os.environ.get("STUDY_ADMIN_KEY"):
        print(f"admin: http://localhost:{a.port}/admin  key {CFG['admin']}", flush=True)
    try:
        srv.serve_forever()
    except KeyboardInterrupt:
        bye()


if __name__ == "__main__":
    main()

#!/bin/bash
# Generates the class-A data of the third confirmatory batch: TPC-C, Epinions and Twitter with the BenchBase build of
# batch 2 (commit 33c0047, the tar of gen_benchbase_linux.sh; scale factor 1, the sample SQLite configs changed only in
# scalefactor and the database path), and Synthea v4.0.0 (synthea-with-dependencies.jar of the GitHub release) with
# 1,000 patients, seed 0, the default state, CSV export on.  Nothing generated is opened; sizes and sha256 go to the
# MANIFEST.tsv of each source directory.
# Usage:  RAW=<dir> RAW2=<dir of batch 2 with benchbase-sqlite.tar> JAVA_HOME=<JDK 23> bash gen_fresh3.sh
set -u
RAW=${RAW:-$PWD/fresh_raw3}
RAW2=${RAW2:-$PWD/fresh_raw2}
T=${T:-$PWD/fresh3_tools}
UA="Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36"
log() { echo "== $* $(date +%T)"; }
export PATH="$JAVA_HOME/bin:$PATH"
java -version 2>&1 | head -1
COMMIT=33c00473807ebd49304d114a6d769d2d2b2bbb34
mkdir -p "$RAW/benchbase" "$RAW/synthea" "$T"
if [ ! -s "$RAW/benchbase/MANIFEST.tsv" ] || ! grep -q twitter.db "$RAW/benchbase/MANIFEST.tsv"; then
  cd "$T" && rm -rf benchbase-sqlite && tar -xf $RAW2/benchbase-sqlite.tar && cd benchbase-sqlite || exit 1
  sha256sum $RAW2/benchbase-sqlite.tar
  printf 'date\tsource\tfile\thttp\tbytes\tsha256\turl\n' > "$RAW/benchbase/MANIFEST.tsv"
  for b in tpcc epinions twitter; do
    log "generate $b"
    sed -e 's#<scalefactor>[^<]*</scalefactor>#<scalefactor>1</scalefactor>#' \
        -e "s#jdbc:sqlite:[^<]*#jdbc:sqlite:$b.db#" "config/sqlite/sample_${b}_config.xml" > "cfg_$b.xml"
    grep -o "<scalefactor>[^<]*</scalefactor>\|jdbc:sqlite:[^<]*" "cfg_$b.xml"
    rm -f "$b.db"
    nice -n 19 java -jar benchbase.jar -b "$b" -c "cfg_$b.xml" --create=true --load=true --execute=false > "$RAW/gen_$b.log" 2>&1 || { tail -20 "$RAW/gen_$b.log"; exit 1; }
    mv "$b.db" "$RAW/benchbase/$b.db"; cp "cfg_$b.xml" "$RAW/benchbase/"
    printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "$(date -u +%FT%TZ)" benchbase "$b.db" generated "$(stat -c %s "$RAW/benchbase/$b.db")" \
      "$(sha256sum "$RAW/benchbase/$b.db" | cut -c1-64)" "generated by BenchBase $COMMIT, scale factor 1" >> "$RAW/benchbase/MANIFEST.tsv"
  done
  cat "$RAW/benchbase/MANIFEST.tsv"
fi
log "synthea"
cd "$RAW/synthea" || exit 1
if [ ! -s synthea-with-dependencies.jar ]; then
  code=$(curl -sSL -A "$UA" --retry 3 --max-time 3600 -o synthea-with-dependencies.jar -w "%{http_code}" https://github.com/synthetichealth/synthea/releases/download/v4.0.0/synthea-with-dependencies.jar)
  printf 'date\tsource\tfile\thttp\tbytes\tsha256\turl\n' > MANIFEST.tsv
  printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "$(date -u +%FT%TZ)" synthea synthea-with-dependencies.jar "$code" "$(stat -c %s synthea-with-dependencies.jar)" \
    "$(sha256sum synthea-with-dependencies.jar | cut -c1-64)" https://github.com/synthetichealth/synthea/releases/download/v4.0.0/synthea-with-dependencies.jar >> MANIFEST.tsv
  echo "jar $code $(stat -c %s synthea-with-dependencies.jar)"
fi
if [ ! -d output/csv ]; then
  nice -n 19 java -jar synthea-with-dependencies.jar -p 1000 -s 0 --exporter.csv.export=true --exporter.fhir.export=false \
    --exporter.hospital.fhir.export=false --exporter.practitioner.fhir.export=false --exporter.baseDirectory=./output > gen_synthea.log 2>&1 || { tail -20 gen_synthea.log; exit 1; }
  tail -5 gen_synthea.log
  for f in output/csv/*.csv; do
    printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "$(date -u +%FT%TZ)" synthea "$(basename $f)" generated "$(stat -c %s "$f")" "$(sha256sum "$f" | cut -c1-64)" \
      "generated by Synthea v4.0.0: -p 1000 -s 0, default state, csv exporter" >> MANIFEST.tsv
  done
  cat MANIFEST.tsv
fi
log "gen_fresh3 done"

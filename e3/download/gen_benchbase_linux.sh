#!/bin/bash
# Generates SEATS, AuctionMark and TATP (BenchBase, scale factor 1) as SQLite files on a Linux server: the loader
# builds class-path resource names with File.separator, so the distribution is built on Linux.
# The built distribution (target/benchbase-sqlite of the pinned commit) is expected as benchbase-sqlite.tar; a Linux
# JDK 23 is fetched from Adoptium into the work directory.  Nothing generated is opened; sha256 go to MANIFEST.tsv.
# Usage:  W=<dir of download_fresh2.sh> bash gen_benchbase_linux.sh <commit>
set -u
COMMIT=$1
W=${W:-$PWD/fresh_raw2}
cd "$W" || exit 1
log() { echo "== $* $(date +%T)"; }
if [ ! -x jdk23/bin/java ]; then
  log "fetch JDK 23 (linux x64)"
  curl -sSL -o jdk23.tar.gz "https://api.adoptium.net/v3/binary/latest/23/ga/linux/x64/jdk/hotspot/normal/eclipse?project=jdk" || exit 1
  sha256sum jdk23.tar.gz > jdk23.tar.gz.sha256
  mkdir -p jdk23 && tar -xzf jdk23.tar.gz -C jdk23 --strip-components=1
fi
export JAVA_HOME="$W/jdk23"; export PATH="$W/jdk23/bin:$PATH"
java -version 2>&1 | head -1
rm -rf benchbase-sqlite && tar -xf benchbase-sqlite.tar && cd benchbase-sqlite || exit 1
mkdir -p "$W/benchbase"
printf 'date\tsource\tfile\thttp\tbytes\tsha256\turl\n' > "$W/benchbase/MANIFEST.tsv"
for b in seats auctionmark tatp; do
  log "generate $b"
  sed -e 's#<scalefactor>[^<]*</scalefactor>#<scalefactor>1</scalefactor>#' \
      -e "s#jdbc:sqlite:[^<]*#jdbc:sqlite:$b.db#" "config/sqlite/sample_${b}_config.xml" > "cfg_$b.xml"
  grep -o "<scalefactor>[^<]*</scalefactor>\|jdbc:sqlite:[^<]*" "cfg_$b.xml"
  rm -f "$b.db"
  nice -n 19 java -jar benchbase.jar -b "$b" -c "cfg_$b.xml" --create=true --load=true --execute=false > "$W/gen_$b.log" 2>&1 || { tail -20 "$W/gen_$b.log"; exit 1; }
  mv "$b.db" "$W/benchbase/$b.db"; cp "cfg_$b.xml" "$W/benchbase/"
  printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "$(date -u +%FT%TZ)" benchbase "$b.db" generated "$(stat -c %s "$W/benchbase/$b.db")" \
    "$(sha256sum "$W/benchbase/$b.db" | cut -c1-64)" "generated by BenchBase $COMMIT, scale factor 1" >> "$W/benchbase/MANIFEST.tsv"
done
cat "$W/benchbase/MANIFEST.tsv"
log "benchbase done"
